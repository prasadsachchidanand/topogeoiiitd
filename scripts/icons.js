'use strict';

// Builds dist/assets/icons.css containing only the Font Awesome icons the site uses.
// Markup keeps the usual classes (`<i class="fas fa-video">`); each icon is drawn as a
// CSS mask filled with currentColor, so colour, size and hover classes work as before.

const fs = require('node:fs');
const path = require('node:path');
const { fas } = require('@fortawesome/free-solid-svg-icons');
const { far } = require('@fortawesome/free-regular-svg-icons');
const { fab } = require('@fortawesome/free-brands-svg-icons');

const PACKS = [
  { classes: ['fas', 'fa-solid'], icons: fas },
  { classes: ['far', 'fa-regular'], icons: far },
  { classes: ['fab', 'fa-brands'], icons: fab }
];
const PREFIX_CLASSES = new Set(PACKS.flatMap((pack) => pack.classes));
const MODIFIERS = new Set(['fw', 'spin', 'pulse', 'xs', 'sm', 'lg', 'xl', '2xl', ...Array.from({ length: 10 }, (_, i) => `${i + 1}x`)]);

function indexPack(icons) {
  const byName = new Map();
  for (const definition of Object.values(icons)) {
    if (!definition?.icon) continue;
    byName.set(definition.iconName, definition);
    for (const alias of definition.icon[2]) if (typeof alias === 'string') byName.set(alias, definition);
  }
  return byName;
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return ['notes', 'data'].includes(entry.name) ? [] : walk(target);
    return /\.(html|js)$/.test(entry.name) ? [target] : [];
  });
}

function svgUrl([width, height, , , pathData]) {
  const d = Array.isArray(pathData) ? pathData.join(' ') : pathData;
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${width} ${height}'><path d='${d}'/></svg>`;
  return `url("data:image/svg+xml,${svg.replace(/[<>#%"]/g, encodeURIComponent)}")`;
}

function usedIconNames(dist) {
  const names = new Set();
  for (const file of walk(dist)) {
    for (const match of fs.readFileSync(file, 'utf8').matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)) {
      if (!MODIFIERS.has(match[1]) && !PREFIX_CLASSES.has(`fa-${match[1]}`)) names.add(match[1]);
    }
  }
  return [...names].sort();
}

function buildIcons(dist) {
  const packs = PACKS.map((pack) => ({ ...pack, byName: indexPack(pack.icons) }));
  const names = usedIconNames(dist);
  const missing = names.filter((name) => !packs.some((pack) => pack.byName.has(name)));
  if (missing.length) {
    throw new Error(`Unknown Font Awesome icon(s): ${missing.map((name) => `fa-${name}`).join(', ')}. Use a free Font Awesome 6 icon name.`);
  }

  const base = [...PREFIX_CLASSES].map((name) => `.${name}`).join(',');
  const rules = [];
  for (const name of names) {
    for (const pack of packs) {
      const definition = pack.byName.get(name);
      if (!definition) continue;
      const [width, height] = definition.icon;
      const prefixes = pack.classes.map((prefix) => `.${prefix}`).join(',');
      // :where() keeps specificity low, so Tailwind width classes such as w-4 still win.
      rules.push(`:where(${prefixes}).fa-${name}{--fa-icon:${svgUrl(definition.icon)};width:${+(width / height).toFixed(4)}em}`);
    }
  }

  const css = `/* Generated by scripts/icons.js from Font Awesome Free 6.7.2 (icons: CC BY 4.0). Do not edit. */
${base}{display:inline-block;flex-shrink:0;width:1em;height:1em;vertical-align:-.125em;font-style:normal;line-height:1;background-color:currentColor;-webkit-mask:var(--fa-icon) center/contain no-repeat;mask:var(--fa-icon) center/contain no-repeat;-webkit-print-color-adjust:exact;print-color-adjust:exact}
:where(${base}).fa-fw{width:1.25em}
.fa-xs{font-size:.75em}.fa-sm{font-size:.875em}.fa-lg{font-size:1.25em}.fa-xl{font-size:1.5em}.fa-2xl{font-size:2em}
${Array.from({ length: 10 }, (_, i) => `.fa-${i + 1}x{font-size:${i + 1}em}`).join('')}
.fa-spin{animation:fa-spin 2s linear infinite}.fa-pulse{animation:fa-spin 1s steps(8) infinite}
@keyframes fa-spin{to{transform:rotate(360deg)}}
@media (prefers-reduced-motion:reduce){.fa-spin,.fa-pulse{animation:none}}
@media (forced-colors:active){${base}{forced-color-adjust:none;background-color:CanvasText}}
${rules.join('\n')}
`;
  fs.mkdirSync(path.join(dist, 'assets'), { recursive: true });
  fs.writeFileSync(path.join(dist, 'assets', 'icons.css'), css);
  return names.length;
}

module.exports = { buildIcons };
